# Writes the design tokens from design/tokens.json into liftbook.html (between the tokens markers).
# design/tokens.json is the same file as tokens.json in the Relief design system artifact.
# Usage: python3 build-tokens.py   (then python3 build-standalone.py for the website file)
import json, os, re
here = os.path.dirname(os.path.abspath(__file__))
t = json.load(open(os.path.join(here, "design", "tokens.json"), encoding="utf-8"))
NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")

ALIAS = re.compile(r"^\{([A-Za-z0-9][A-Za-z0-9_-]*)\}$")  # "{other-token}" = the same colour as another token

def css_value(v, known):
    m = ALIAS.match(v)
    if not m: return v
    assert m.group(1) in known, "alias of a missing token: " + v
    return f"var(--{m.group(1)})"

def per_theme(tokens):
    """(name, light value, dark value) for every token; a plain value is the same in both themes."""
    known = {x["name"] for x in tokens}
    out = []
    for x in tokens:
        assert NAME.match(x["name"]), "token name not usable in CSS: " + x["name"]
        v = x["value"]
        l, d = (v, v) if isinstance(v, str) else (v.get("light", v["dark"]), v.get("dark", v["light"]))
        out.append((x["name"], css_value(l, known), css_value(d, known)))
    return out

colors = per_theme(t["color"]["tokens"]) + per_theme(t.get("shadow", {}).get("tokens", []))
plain = [(x["name"], x["value"]) for f in ("spacing", "radius", "size") for x in t.get(f, {}).get("tokens", [])]
fams = t["type"]["families"]  # keys become --display, --body (the names the app's CSS uses)

light = "; ".join(f"--{n}: {l}" for n, l, d in colors)
dark = "; ".join(f"--{n}: {d}" for n, l, d in colors if l != d) + "; color-scheme: dark;"
rest = "; ".join([f"--{n}: {v}" for n, v in plain] + [f"--{k}: {v}" for k, v in fams.items()]
                 + ["--tabbar: calc(var(--tabbar-h) + var(--tabbar-gap))"])  # = the room the floating menu takes above the safe area
block = (
    "/* Generated by build-tokens.py from design/tokens.json: change colours there, not here. */\n"
    f":root {{ {light};\n  {rest}; }}\n"
    f"@media (prefers-color-scheme: dark) {{ :root:not([data-theme=\"light\"]) {{ {dark} }} }}\n"
    f":root[data-theme=\"dark\"] {{ {dark} }}\n"
)
path = os.path.join(here, "liftbook.html")
s = open(path, encoding="utf-8").read()
start, end = "/* <tokens:start> */", "/* <tokens:end> */"
a, b = s.index(start) + len(start), s.index(end)
s = s[:a] + "\n" + block + s[b:]
open(path, "w", encoding="utf-8").write(s)
print("wrote", len(colors), "colour/shadow tokens and", len(plain) + len(fams), "other tokens")
